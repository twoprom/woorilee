// k1b-report.md generation (docs/plans/hanja-context-scaling-plan.md §12 K1b Part 1).
import Foundation

let candidateCountBucketOrder = ["1", "2", "3-5", "6-10", "11-20", "21+"]
let reuseBucketOrder = ["1", "2-5", "6-10", "11+"]

func mdTable(_ title: String, _ tallies: [String: Tally], order: [String]? = nil) -> String {
    var out = "\n| \(title) | n | correct | top1 |\n|---|---:|---:|---:|\n"
    let keys = order ?? tallies.keys.sorted()
    for k in keys {
        guard let t = tallies[k] else { continue }
        out += String(format: "| %@ | %d | %d | %.1f%% |\n", k, t.total, t.correct, t.pct)
    }
    return out
}

func writeK1bReport(
    options: K1bOptions, donorRows: [DonorRow], inventory: TargetInventory,
    fitRows: [MeasureRow], holdoutRows: [MeasureRow],
    fitFamilies: Set<String>, holdoutFamilies: Set<String>,
    joinMismatches: Int, readingsOfInterest: [String],
    holdoutPageIds: Set<String>, scannedLines: Int, excludedByPageId: Int,
    totalRawHits: Int, totalCollected: Int, occurrenceReadingCount: Int,
    verifiedOccurrences: Int, totalOccurrences: Int, baselinePairCount: Int,
    fitScored: [ScoredRow], holdoutScored: [ScoredRow],
    fitSurface: [String: SurfaceCell], holdoutSurface: [String: SurfaceCell],
    ubiquitousDonors: Set<String>,
    sourceScoreOf: (ScoredRow) -> Int, reuseCountOf: (ScoredRow) -> Int, tierOf: (ScoredRow) -> String,
    evalCorrect: Int, evalScored: Int, evalUncoveredOrNoBaseline: Int, evalTotal: Int,
    msPerSentence: Double, collectElapsed: Double, baselineElapsed: Double
) throws {
    var md = "# K1b Part 1 report — non-transductive donor baseline + coverage-bracket narrowing\n\n"
    md += "Generated by `scripts/hanja-context/k1 k1b --cap \(options.capPerReading) --topn \(options.topN)`. "
        + "docs/plans/hanja-context-scaling-plan.md §12 K1b. Measurement set (`measure/{fit,holdout}.tsv`) was "
        + "built by the coordinator, not by this run — this report only reads it.\n\n"

    // --- 1. measurement basis recap ---
    md += "## 1. Measurement basis\n\n"
    md += "D1 target-restricted token seeds 62,273 rows -> leak filter (gold hanja string still present "
        + "in `input_sentence`) -> 61,301 survive -> restricted to donor-covered pairs -> "
        + "**fit \(fitRows.count) rows / holdout \(holdoutRows.count) rows** (measure/{fit,holdout}.tsv, as built).\n\n"
    md += "**Family-disjointness (re-verified here, not assumed)**: fit \(fitFamilies.count) families, "
        + "holdout \(holdoutFamilies.count) families, intersection **\(fitFamilies.intersection(holdoutFamilies).count)** "
        + "(must be 0 — checked programmatically before any scoring ran; the run aborts otherwise).\n\n"
    md += "**Join sanity vs donors.tsv**: \(joinMismatches) mismatches out of \(fitRows.count + holdoutRows.count) rows "
        + "(reading/candidate/sense_id/donor/donor_pos/source all cross-checked; expect 0).\n\n"
    md += "**readingsOfInterest** (union of fit+holdout distinct readings, the universe needing a baseline): "
        + "\(readingsOfInterest.count).\n\n"

    // --- 2. baseline sample construction ---
    md += "## 2. Wiki-sample baseline construction (K1b-1, non-transductive)\n\n"
    md += "**Correction from the original brief**: baselines are estimated from an independent wiki sample "
        + "(`filtered/part-*.txt`), not from fit-split gold rows — 23% of holdout's unique pairs have zero "
        + "fit-split occurrences, which would have left them unmeasurable under the original fit-centering design.\n\n"
    md += "**Holdout-leakage exclusion, concretely**: every filtered-corpus line whose `page_id` is one of the "
        + "**\(holdoutPageIds.count)** distinct holdout page_ids is skipped before any pattern matching runs "
        + "(checked first, cheapest reject). On top of that, a line surviving the page filter is still dropped "
        + "per-reading if it literally contains any of that reading's own candidate hanja strings (e.g. "
        + "`가경(嘉慶)` — confirmed present verbatim in holdout page 1006140's raw filtered line, independently "
        + "of the page_id exclusion, which is why both guards are applied).\n\n"
    md += String(format: "- Scanned %d filtered-corpus lines, excluded %d by holdout page_id, %d raw bigram-index hits, "
        + "%d occurrences kept after per-reading cap (%d) + leak-guard, spanning %d/%d readings with >=1 kept occurrence "
        + "(%.1fs scan)\n", scannedLines, excludedByPageId, totalRawHits, totalCollected, options.capPerReading,
        occurrenceReadingCount, readingsOfInterest.count, collectElapsed)
    md += String(format: "- Kiwi verification (does a token with form==reading really sit at the scanned position?): "
        + "%d/%d occurrences verified (%.1f%%) in %.1fs -> **%d (reading,candidate) pairs have >=1 baseline sample**\n\n",
        verifiedOccurrences, totalOccurrences, totalOccurrences > 0 ? Double(verifiedOccurrences) / Double(totalOccurrences) * 100 : 0,
        baselineElapsed, baselinePairCount)
    md += "Full manifest: `baseline-occurrences.tsv` (raw, pre-verification). Per-pair means: `baseline-stats.tsv`.\n\n"

    // --- 3. coverage gap: uncovered / no-baseline, per split ---
    md += "## 3. Coverage gap after baseline construction\n\n"
    md += "| split | scored | uncovered (no donor) | noBaseline (donor, but 0 wiki-sample occurrences) |\n|---|---:|---:|---:|\n"
    for (name, rows) in [("fit", fitScored), ("holdout", holdoutScored)] {
        let uncovered = rows.filter { $0.status == "uncovered" }.count
        let noBaseline = rows.filter { $0.status == "noBaseline" }.count
        let scored = rows.filter { $0.status == "scored" }.count
        md += "| \(name) | \(scored) | \(uncovered) | \(noBaseline) |\n"
    }
    md += "\n(`uncovered` should be ~0 by construction — measure/*.tsv was already restricted to donor-covered pairs; "
        + "`noBaseline` is the residual gap the wiki-sample design was meant to close relative to fit-only centering.)\n\n"

    // --- 4. sense surfacing rate ---
    md += "## 4. Sense surfacing rate by candidate count (fit+holdout combined)\n\n"
    md += "A cell = (row, donor-covered candidate of that row's reading). \"Surfaced\" = that candidate's "
        + "registered sense appeared SOMEWHERE in the topN=\(options.topN) parse list at the row's target position "
        + "— missing is a measurement gap, not a low score, and is excluded from the argmax rather than penalized "
        + "with a fabricated score.\n\n"
    var mergedSurface: [String: SurfaceCell] = fitSurface
    for (k, v) in holdoutSurface {
        var c = mergedSurface[k] ?? SurfaceCell()
        c.surfaced += v.surfaced
        c.total += v.total
        mergedSurface[k] = c
    }
    md += "| candidate count | cells | surfaced | surfacing rate |\n|---|---:|---:|---:|\n"
    for bucket in candidateCountBucketOrder {
        guard let c = mergedSurface[bucket], c.total > 0 else { continue }
        md += String(format: "| %@ | %d | %d | %.1f%% |\n", bucket, c.total, c.surfaced, Double(c.surfaced) / Double(c.total) * 100)
    }
    md += "\n"

    // holdout row distribution by candidate count (cross-check vs the coordinator's stated 11-20:18.7% / 21+:3.4%)
    var holdoutDist: [String: Int] = [:]
    for r in holdoutRows {
        let n = inventory.candidatesByReading[r.reading]?.count ?? 1
        holdoutDist[candidateCountBucket(n), default: 0] += 1
    }
    md += "Holdout ROW distribution by reading's candidate count (cross-check against the coordinator's stated "
        + "figures):\n\n| candidate count | rows | % of holdout |\n|---|---:|---:|\n"
    for bucket in candidateCountBucketOrder {
        guard let n = holdoutDist[bucket], n > 0 else { continue }
        md += String(format: "| %@ | %d | %.1f%% |\n", bucket, n, Double(n) / Double(holdoutRows.count) * 100)
    }
    md += "\n"

    // --- 5. holdout accuracy breakdowns (the headline measurement) ---
    md += "## 5. Holdout top1 accuracy, by axis\n\n"
    let holdoutScoredOnly = holdoutScored.filter { $0.status == "scored" }
    let fitScoredOnly = fitScored.filter { $0.status == "scored" }
    md += String(format: "**Overall holdout top1 (scored rows only): %d/%d = %.1f%%**\n",
        holdoutScoredOnly.filter(\.correct).count, holdoutScoredOnly.count,
        holdoutScoredOnly.isEmpty ? 0 : Double(holdoutScoredOnly.filter(\.correct).count) / Double(holdoutScoredOnly.count) * 100)
    let noSurfaceMisses = holdoutScoredOnly.filter(\.noSurfaceMiss).count
    md += "(\(noSurfaceMisses)/\(holdoutScoredOnly.count) of those are \"no-surface misses\" — none of the "
        + "competing candidates' senses surfaced at all, so no real prediction was possible; counted as incorrect, "
        + "not excluded.)\n\n"

    md += "### by donor source (gold pair's own source)\n" + mdTable("source", tallyBy(holdoutScoredOnly) { $0.source })
    md += "\n### by NIKL 판별도 (source_score) — exact partition (1 / 2 / 3+)\n"
    let niklOnly = holdoutScoredOnly.filter { $0.source == "nikl" }
    md += mdTable("판별도", tallyBy(niklOnly) { s in let v = sourceScoreOf(s); return v >= 3 ? "3+" : (v == 2 ? "2" : "1") },
        order: ["1", "2", "3+"])
    md += "\n### by NIKL 판별도 — cumulative threshold (as literally asked: 1 / ≥2 / ≥3, NOT mutually exclusive — ≥3 ⊂ ≥2)\n"
    md += "\n| threshold | n | correct | top1 |\n|---|---:|---:|---:|\n"
    let niklScores = niklOnly.map { ($0, sourceScoreOf($0)) }
    let thresholds: [(String, Int)] = [("all nikl (≡ ≥1)", 1), ("≥2", 2), ("≥3", 3)]
    for (label, minScore) in thresholds {
        let subset = niklScores.filter { $0.1 >= minScore }.map(\.0)
        let correct = subset.filter(\.correct).count
        md += String(format: "| %@ | %d | %d | %.1f%% |\n", label, subset.count, correct, subset.isEmpty ? 0 : Double(correct) / Double(subset.count) * 100)
    }
    md += "\n### by donor reuse count (global, across all of donors.tsv)\n"
    md += mdTable("reuse", tallyBy(holdoutScoredOnly) { reuseBucket(reuseCountOf($0)) }, order: reuseBucketOrder)
    md += "\n### by reading's candidate count\n"
    md += mdTable("candidates", tallyBy(holdoutScoredOnly) { candidateCountBucket($0.candidateCount) }, order: candidateCountBucketOrder)

    // --- 6. coverage bracket narrowing: nested tier accuracy, fit (sanity) vs holdout (reported) ---
    md += "\n## 6. Coverage-bracket narrowing — nested tier accuracy\n\n"
    md += "Tiers reuse K1a's own structural definitions (never re-derived from fit/holdout — no circularity risk): "
        + "**tier 1** = anchor+assoc sources (K1a's 17.3% lower bound, 3,365/19,490); **tier 2 (incremental)** = "
        + "nikl donors with 판별도≥2 AND not in the reused->=11-pairs set (K1a's provisional 21.3% tier, minus tier 1); "
        + "**tier 3 (incremental)** = remaining nikl donors (판별도==1, or reused>=11 pairs) — the rest of the 86.5% "
        + "upper bound. Reuse-count here is computed over donors.tsv's FINAL registered rows (a proxy for K1a's "
        + "candidate-pool-based ubiquity count, §k1a report footnote — likely under-flags some ubiquitous donors "
        + "since the final set is smaller than the pool K1a filtered from; the accuracy PATTERN below is the "
        + "informative part, not an exact reproduction of K1a's 780-pair tier size).\n\n"
    for (label, rows) in [("fit (sanity check)", fitScoredOnly), ("holdout (reported)", holdoutScoredOnly)] {
        md += "### \(label)\n\n| tier | n | correct | top1 | cumulative n | cumulative top1 |\n|---|---:|---:|---:|---:|---:|\n"
        let t1 = rows.filter { tierOf($0) == "1_anchor+assoc" }
        let t2 = rows.filter { tierOf($0) == "2_plus3filterNikl" }
        let t3 = rows.filter { tierOf($0) == "3_plusRawOnlyNikl" }
        let cum1 = t1
        let cum2 = t1 + t2
        let cum3 = t1 + t2 + t3
        func acc(_ r: [ScoredRow]) -> Double { r.isEmpty ? 0 : Double(r.filter(\.correct).count) / Double(r.count) * 100 }
        md += String(format: "| 1_anchor+assoc | %d | %d | %.1f%% | %d | %.1f%% |\n", t1.count, t1.filter(\.correct).count, acc(t1), cum1.count, acc(cum1))
        md += String(format: "| 2_+3filterNikl (incremental) | %d | %d | %.1f%% | %d | %.1f%% |\n", t2.count, t2.filter(\.correct).count, acc(t2), cum2.count, acc(cum2))
        md += String(format: "| 3_+rawOnlyNikl (incremental) | %d | %d | %.1f%% | %d | %.1f%% |\n\n", t3.count, t3.filter(\.correct).count, acc(t3), cum3.count, acc(cum3))
    }

    // --- 7. floor baselines ---
    md += "## 7. Floor baselines (same holdout scored rows)\n\n"
    let floorACorrect = holdoutScoredOnly.filter(\.floorACorrect).count
    let floorBExpectedSum = holdoutScoredOnly.map(\.floorBExpected).reduce(0, +)
    md += String(format: "- (a) most-frequent-candidate-by-freq (runtime dominant-map logic, rank-1 of targets.tsv, "
        + "no donor/Kiwi involved): **%d/%d = %.1f%%**\n", floorACorrect, holdoutScoredOnly.count,
        holdoutScoredOnly.isEmpty ? 0 : Double(floorACorrect) / Double(holdoutScoredOnly.count) * 100)
    md += String(format: "- (b) uniform random over the reading's full candidate inventory (analytic expectation "
        + "mean(1/candidateCount), not simulated): **%.1f%%** (E[correct]=%.2f of %d)\n\n",
        holdoutScoredOnly.isEmpty ? 0 : floorBExpectedSum / Double(holdoutScoredOnly.count) * 100,
        floorBExpectedSum, holdoutScoredOnly.count)
    md += "K1's own overall holdout top1 (§5) sits against these two floors — see §8 for the headline read.\n\n"

    // --- 8. secondary direction-only 258-eval check ---
    md += "## 8. Secondary check — 258-row eval set (direction-only, NOT used for selection — 계획 §13)\n\n"
    md += String(format: "%d/%d scored top1 = **%.1f%%** (%d/%d rows excluded as uncovered/no-baseline). "
        + "Reported for direction only; never used to pick thresholds or tune anything above.\n\n",
        evalCorrect, evalScored, evalScored > 0 ? Double(evalCorrect) / Double(evalScored) * 100 : 0,
        evalUncoveredOrNoBaseline, evalTotal)

    // --- 9. throughput ---
    md += "## 9. Throughput\n\n"
    md += String(format: "%.4f ms/sentence at topN=%d (300-row probe). Full run: corpus scan %.1fs, "
        + "baseline verification %.1fs, row scoring — see stdout log for the exact wall-clock split.\n\n",
        msPerSentence, options.topN, collectElapsed, baselineElapsed)

    md += "## 10. Determinism\n\n"
    md += "All accumulation that feeds a printed float (baseline means) iterates in a FIXED, file-scan/"
        + "sorted-key order — never raw `Dictionary`/`Set` iteration, which Swift randomizes per process. "
        + "Confirmed by running this command twice and diffing every file under `k1/` (see chat report for the "
        + "actual diff — this paragraph is generated before that check, not after).\n\n"

    try md.write(to: Paths.outDir.appendingPathComponent("k1b-report.md"), atomically: true, encoding: .utf8)
    print("wrote \(Paths.outDir.appendingPathComponent("k1b-report.md").path)")
}
