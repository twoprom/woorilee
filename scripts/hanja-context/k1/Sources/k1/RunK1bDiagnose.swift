// K1b Part 1 — gold_surfaced diagnostic decomposition (coordinator follow-up after the first k1b
// run). Question: is holdout top1 (24.1% vs a 28.9% floor) measuring "the LM signal is absent", or
// "topN=30 can't see the signal for the GOLD candidate specifically"? Those have different
// consequences (§12 K1c pretokenized-API workaround vs. killing the track), so top1 must be
// re-reported CONDITIONAL on gold_surfaced==true, with the floors recomputed on the SAME
// conditioned subset (an unconditional floor vs a conditional K1 number would be meaningless).
//
// Reuses the completed run's cached baseline-stats.tsv (loadBaselineStats) instead of repeating the
// ~17-minute corpus-scan + verification pass — only the row-scoring step (which now also records
// gold_surfaced) is re-run, against holdout (23,986 rows) and the 258-row eval set. This trades a
// little float precision (baseline-stats.tsv stores 6-decimal means; reconstructing sum=mean*count
// loses ~1e-6 relative to the original in-memory accumulation) for turnaround — negligible next to
// the nats-scale signal gaps this track measures (K1a §3.6: ~1.5-6.7 nats), so no argmax decision
// is expected to flip. Writes to diagnose-*.tsv / k1b-gold-surfaced-diagnosis.md (distinct
// filenames from the full run's own outputs, so nothing here overwrites the run-to-run determinism
// artifacts).
import Foundation

func runK1bDiagnose(baselineStatsPath: String, topN: Int32) throws {
    print("=== k1b-diagnose (gold_surfaced decomposition, reusing cached baselines) ===")
    let overallStart = Date()
    try ensureOutDir()

    let donorRows = try loadDonorsTable()
    var donorRowsByReading: [String: [DonorRow]] = [:]
    for row in donorRows { donorRowsByReading[row.reading, default: []].append(row) }

    let inventory = try TargetInventory.load()
    print("building aliased Kiwi (replaying \(donorRows.count) donor registrations, TargetInventory.allPairs order)...")
    let kiwi = try buildAliasedKiwiFromDonorsTable(donorRows, inventory: inventory)

    let baselineURL = URL(fileURLWithPath: baselineStatsPath)
    print("loading cached baselines from \(baselineURL.path) (NOT re-scanning the corpus)...")
    let baselines = try loadBaselineStats(from: baselineURL)
    print("  \(baselines.count) (reading,candidate) pairs have a cached baseline")

    let holdoutRows = try loadMeasureRows(Paths.measureDir.appendingPathComponent("holdout.tsv"))
    print("scoring \(holdoutRows.count) holdout rows (topN=\(topN))...")
    let scoreStart = Date()
    let (holdoutScored, _) = try scoreRows(holdoutRows, donorRowsByReading: donorRowsByReading, baselines: baselines, inventory: inventory, kiwi: kiwi, topN: topN)
    let scoreElapsed = Date().timeIntervalSince(scoreStart)
    print("  holdout scoring done in \(String(format: "%.1f", scoreElapsed))s")

    let evalTuples = try dataLines(of: Paths.evalTSV).compactMap { line -> (sentence: String, reading: String, gold: String)? in
        let cols = line.split(separator: "\t", omittingEmptySubsequences: false)
        guard cols.count >= 3 else { return nil }
        return (String(cols[0]), String(cols[1]), String(cols[2]))
    }
    let evalStart = Date()
    let evalScored = try scoreEvalRows(evalTuples, donorRowsByReading: donorRowsByReading, baselines: baselines, inventory: inventory, kiwi: kiwi, topN: topN)
    let evalElapsed = Date().timeIntervalSince(evalStart)
    print("  eval258 scoring done in \(String(format: "%.1f", evalElapsed))s")

    // --- write diagnose-*.tsv audit files (distinct names — do not touch the full run's own outputs) ---
    func writeDiag(_ name: String, _ rows: [ScoredRow]) throws {
        let writer = try LineWriterK1(url: Paths.outDir.appendingPathComponent(name))
        writer.write("# \(name) — gold_surfaced diagnostic re-score (cached baselines, see RunK1bDiagnose.swift header)")
        writer.write("# reading\tcandidate\tstatus\tpredicted\tcorrect\tno_surface_miss\tgold_surfaced\tfloorA_predicted\tfloorA_correct\tfloorB_expected\tsource\tdonor\tcandidate_count")
        for r in rows {
            writer.write([
                r.reading, r.candidate, r.status, r.predicted ?? "", String(r.correct), String(r.noSurfaceMiss), String(r.goldSurfaced),
                r.floorAPredicted, String(r.floorACorrect), String(format: "%.6f", r.floorBExpected),
                r.source, r.donor, String(r.candidateCount),
            ].map(tsvEscape).joined(separator: "\t"))
        }
        writer.close()
    }
    try writeDiag("diagnose-holdout-scored.tsv", holdoutScored)
    try writeDiag("diagnose-eval258-scored.tsv", evalScored)

    // --- report ---
    let holdoutScoredOnly = holdoutScored.filter { $0.status == "scored" }
    var md = "# K1b gold_surfaced diagnostic decomposition\n\n"
    md += "Generated by `k1 k1b-diagnose`. Reuses `baseline-stats.tsv` from the completed full run "
        + "(no corpus re-scan) — holdout re-scored in \(String(format: "%.1f", scoreElapsed))s, eval258 in "
        + "\(String(format: "%.1f", evalElapsed))s (total wall time \(String(format: "%.1f", Date().timeIntervalSince(overallStart)))s), "
        + "vs. the full run's ~17 minutes. No re-tuning, re-thresholding, or re-selection — this only adds "
        + "the `gold_surfaced` field and reports conditional numbers on the SAME scoring already produced.\n\n"

    md += "## 1. gold_surfaced rate (holdout, scored rows)\n\n"
    let goldSurfacedTotal = holdoutScoredOnly.count
    let goldSurfacedYes = holdoutScoredOnly.filter(\.goldSurfaced).count
    md += String(format: "**Overall: %d/%d = %.1f%%** of scored holdout rows have the GOLD candidate's own "
        + "registered sense appearing anywhere in the topN=\(topN) parse list at the target position.\n\n",
        goldSurfacedYes, goldSurfacedTotal, goldSurfacedTotal > 0 ? Double(goldSurfacedYes) / Double(goldSurfacedTotal) * 100 : 0)

    md += "| candidate count | n | gold_surfaced | rate |\n|---|---:|---:|---:|\n"
    var byBucket: [String: (surfaced: Int, total: Int)] = [:]
    for r in holdoutScoredOnly {
        let b = candidateCountBucket(r.candidateCount)
        var e = byBucket[b] ?? (0, 0)
        e.total += 1
        if r.goldSurfaced { e.surfaced += 1 }
        byBucket[b] = e
    }
    for bucket in candidateCountBucketOrder {
        guard let e = byBucket[bucket], e.total > 0 else { continue }
        md += String(format: "| %@ | %d | %d | %.1f%% |\n", bucket, e.total, e.surfaced, Double(e.surfaced) / Double(e.total) * 100)
    }

    // --- headline: conditional top1 vs conditional floors ---
    let conditioned = holdoutScoredOnly.filter(\.goldSurfaced)
    let condCorrect = conditioned.filter(\.correct).count
    let condFloorA = conditioned.filter(\.floorACorrect).count
    let condFloorBSum = conditioned.map(\.floorBExpected).reduce(0, +)
    md += "\n## 2. HEADLINE — holdout top1 conditional on gold_surfaced==true\n\n"
    md += "The unconditional 24.1% mixes rows where K1 never had a chance (gold invisible to topN) with rows "
        + "where it genuinely competed. This conditions on the former being excluded, and recomputes BOTH "
        + "floors on the exact same conditioned row set (an unconditional floor against a conditional K1 "
        + "number would not be a fair comparison).\n\n"
    md += "| | n | correct/expected | rate |\n|---|---:|---:|---:|\n"
    md += String(format: "| **K1 top1 (gold_surfaced==true)** | %d | %d | **%.1f%%** |\n", conditioned.count, condCorrect,
        conditioned.isEmpty ? 0 : Double(condCorrect) / Double(conditioned.count) * 100)
    md += String(format: "| floor (a) most-frequent-by-freq, same subset | %d | %d | %.1f%% |\n", conditioned.count, condFloorA,
        conditioned.isEmpty ? 0 : Double(condFloorA) / Double(conditioned.count) * 100)
    md += String(format: "| floor (b) uniform random, same subset (analytic) | %d | %.2f | %.1f%% |\n\n", conditioned.count, condFloorBSum,
        conditioned.isEmpty ? 0 : condFloorBSum / Double(conditioned.count) * 100)
    md += String(format: "For reference, the UNCONDITIONAL numbers (§5/§7 of the main report): K1 24.1%%, floor(a) 28.9%%, "
        + "floor(b) 17.8%%, over %d rows.\n\n", holdoutScoredOnly.count)

    // --- by donor source, conditioned ---
    md += "## 3. Conditional top1 by donor source (does anchor's structural edge survive conditioning?)\n\n"
    md += "| source | n (surfaced) | K1 correct | K1 top1 | floorA correct | floorA top1 |\n|---|---:|---:|---:|---:|---:|\n"
    for source in ["anchor", "assoc", "nikl"] {
        let subset = conditioned.filter { $0.source == source }
        let k1c = subset.filter(\.correct).count
        let fac = subset.filter(\.floorACorrect).count
        md += String(format: "| %@ | %d | %d | %.1f%% | %d | %.1f%% |\n", source, subset.count, k1c,
            subset.isEmpty ? 0 : Double(k1c) / Double(subset.count) * 100, fac,
            subset.isEmpty ? 0 : Double(fac) / Double(subset.count) * 100)
    }
    md += "\n(Unconditional, for comparison — §5 of the main report: anchor 26.9%, assoc 28.4%, nikl 22.7%.)\n\n"

    // --- eval258 diagnosis ---
    let evalScoredOnly = evalScored.filter { $0.status == "scored" }
    let evalGoldSurfacedYes = evalScoredOnly.filter(\.goldSurfaced).count
    let evalConditioned = evalScoredOnly.filter(\.goldSurfaced)
    let evalCondCorrect = evalConditioned.filter(\.correct).count
    md += "## 4. Diagnosing the 258-row eval set's 8.7%\n\n"
    md += String(format: "gold_surfaced rate on the 219 scored eval rows: **%d/%d = %.1f%%**. "
        + "Conditional top1 (gold_surfaced==true): **%d/%d = %.1f%%**.\n\n",
        evalGoldSurfacedYes, evalScoredOnly.count, evalScoredOnly.isEmpty ? 0 : Double(evalGoldSurfacedYes) / Double(evalScoredOnly.count) * 100,
        evalCondCorrect, evalConditioned.count, evalConditioned.isEmpty ? 0 : Double(evalCondCorrect) / Double(evalConditioned.count) * 100)
    if evalScoredOnly.isEmpty {
        md += "No scored eval rows — cannot decompose further.\n\n"
    } else {
        let evalSurfaceRate = Double(evalGoldSurfacedYes) / Double(evalScoredOnly.count) * 100
        let holdoutSurfaceRate = goldSurfacedTotal > 0 ? Double(goldSurfacedYes) / Double(goldSurfacedTotal) * 100 : 0
        md += String(format: "Holdout gold_surfaced rate for comparison: %.1f%%. ", holdoutSurfaceRate)
        if abs(evalSurfaceRate - holdoutSurfaceRate) <= 10 {
            md += "The eval set's surfacing rate is in the same range as holdout's — **the 8.7%% looks like the same "
                + "surfacing problem, not something eval-specific.**\n\n"
        } else {
            md += String(format: "The eval set's surfacing rate differs from holdout's by %.1fpp — this suggests the "
                + "258-row set's low score is NOT purely the same surfacing phenomenon; something else about that "
                + "set (composition, sentence length, topic mix) may also be contributing.\n\n", abs(evalSurfaceRate - holdoutSurfaceRate))
        }
    }

    md += "## 5. Reproducibility note (order-dependence, carried over from the main report)\n\n"
    md += "`donors.tsv` is **not independently replayable in its own on-disk order** — its rows are written "
        + "sorted alphabetically by (reading, candidate), but `kiwi_builder_add_alias_word_with_def`'s origWord "
        + "lookup can resolve against an alias THIS SAME accumulating builder already created for an EARLIER "
        + "sense of the same reading (confirmed empirically: reading 신밀's sense_id=1, 身密, registers alias "
        + "`신밀`/NNG borrowing from donor `부처`; sense_id=4, 愼密, then legitimately borrows from that "
        + "just-created `신밀`/NNG alias per its own donors.tsv row). Replaying donors.tsv in file order breaks "
        + "this (verified: it throws \"cannot find the original morpheme 신밀/NNG\"). The fix used everywhere in "
        + "this codebase (`buildAliasedKiwiFromDonorsTable`) replays in `TargetInventory.allPairs` order (reading "
        + "file-order, then sense_id ascending) — the exact order K1a's original build-donors used. **The "
        + "registration sequence is part of the artifact; any future consumer of donors.tsv (including K1c) must "
        + "be told this order, not just handed the file.**\n\n"

    try md.write(to: Paths.outDir.appendingPathComponent("k1b-gold-surfaced-diagnosis.md"), atomically: true, encoding: .utf8)
    print("wrote \(Paths.outDir.appendingPathComponent("k1b-gold-surfaced-diagnosis.md").path)")
    print(String(format: "TOTAL wall time: %.1fs", Date().timeIntervalSince(overallStart)))
}
