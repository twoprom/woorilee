// k1a-coverage.md generation (Part 3 rewrite, coordinator review) — coverage reported as a
// BRACKET across filter tiers, never a single headline number. Denominator is always 19,490
// (전체 표적 쌍) except for the anchor-alone row, where 8,127 (anchor-having pairs) is the
// pre-registered baseline's own denominator and stays meaningful.
import Foundation

func pct(_ n: Int, _ total: Int) -> Double {
    total == 0 ? 0 : Double(n) / Double(total) * 100
}

struct D1Comparison {
    let label: String
    let k1Count: Int
    let intersection: Int
    let union: Int
    let k1OnlyNoD1: Int
    let d1OnlyNoK1: Int
}

func compareToD1(label: String, k1Set: Set<PairKey>, d1Pairs: Set<PairKey>) -> D1Comparison {
    D1Comparison(
        label: label,
        k1Count: k1Set.count,
        intersection: k1Set.intersection(d1Pairs).count,
        union: k1Set.union(d1Pairs).count,
        k1OnlyNoD1: k1Set.subtracting(d1Pairs).count,
        d1OnlyNoK1: d1Pairs.subtracting(k1Set).count
    )
}

func writeCoverageReport(
    inventory: TargetInventory,
    anchorOnlySet: Set<PairKey>,
    assocOnlySet: Set<PairKey>,
    anchorAssocSet: Set<PairKey>,
    niklRawOnlySet: Set<PairKey>,
    niklDisc2OnlySet: Set<PairKey>,
    niklDisc2UbiqOnlySet: Set<PairKey>,
    rawTierSet: Set<PairKey>,
    threeFilterTierSet: Set<PairKey>,
    officialCoveredSet: Set<PairKey>,
    d1Pairs: Set<PairKey>,
    nativeTagFallbackCount: Int,
    bothTagCount: Int,
    ubiquitousDonorCount: Int,
    baselineBuildTime: TimeInterval,
    aliasedBuildTime: TimeInterval,
    aliasedBuildOnlyTime: TimeInterval,
    registrationElapsed: TimeInterval,
    failureCount: Int,
    regressions: [RegressionRow],
    evalSentenceCount: Int,
    aliasedKiwi: KiwiRaw,
    donorRowsForSpotCheck: [DonorRow]
) throws {
    let totalPairs = inventory.allPairs.count // 19,490-ish
    let anchorHavingPairs8127 = 8127 // the pre-registered baseline's own denominator, anchor-only

    var md = "# K1a-2/K1a-3 donor inventory and coverage (Part 3 — post POS-fix)\n\n"
    md += "Generated by `scripts/hanja-context/k1 build-donors`. **Coverage is reported as a bracket, "
        + "not a headline number** — do not read any single tier as \"the\" coverage figure. Quality "
        + "(which tier actually lands in a usable place) is explicitly **K1b's job, unresolved here**.\n\n"

    md += "## POS-category fix (coordinator review, Part 3 task A)\n\n"
    md += "`kiwi_builder_add_alias_word_with_def` takes ONE `pos` for both the alias (the reading "
        + "itself) and the donor lookup. The original pipeline let any donor's own tag decide this "
        + "pos — so a NIKL donor tagged VA/VV/MAG/XR registered the READING ITSELF as an adjective/"
        + "verb/adverb/root, a category error (target readings are 한자어 nouns). **Fixed**: every "
        + "registration is now restricted to a POS the reading itself natively carries, determined "
        + "empirically by analyzing the bare reading with the plain Kiwi (NativeTags.swift). "
        + "\(nativeTagFallbackCount)/\(inventory.candidatesByReading.count) readings never resolved as "
        + "a single native noun token at all and fell back to the documented {NNG} default assumption. "
        + "\(bothTagCount) readings are natively both NNG and NNP.\n\n"

    md += "## Coverage bracket (denominator = \(totalPairs), 전체 표적 쌍 — see note on 8,127 below)\n\n"
    md += "| tier | pairs | % of \(totalPairs) |\n|---|---:|---:|\n"
    md += String(format: "| anchor 단독 | %d | %.1f%% |\n", anchorOnlySet.count, pct(anchorOnlySet.count, totalPairs))
    md += String(format: "| assoc 단독 | %d | %.1f%% |\n", assocOnlySet.count, pct(assocOnlySet.count, totalPairs))
    md += String(format: "| **anchor+assoc (lower bound — synonym/collocate donors only, no NIKL)** | **%d** | **%.1f%%** |\n",
        anchorAssocSet.count, pct(anchorAssocSet.count, totalPairs))
    md += String(format: "| nikl 원본 (native-tag-fixed, no quality filter) | %d | %.1f%% |\n", niklRawOnlySet.count, pct(niklRawOnlySet.count, totalPairs))
    md += String(format: "| nikl +판별도≥2 (drop source_score==1) | %d | %.1f%% |\n", niklDisc2OnlySet.count, pct(niklDisc2OnlySet.count, totalPairs))
    md += String(format: "| nikl +판별도≥2 +범용기증자 제외 (donor reused in >=11 pairs dropped, %d donor strings excluded) | %d | %.1f%% |\n",
        ubiquitousDonorCount, niklDisc2UbiqOnlySet.count, pct(niklDisc2UbiqOnlySet.count, totalPairs))
    md += String(format: "| **anchor+assoc+nikl(3중 필터) — provisional middle** | **%d** | **%.1f%%** |\n",
        threeFilterTierSet.count, pct(threeFilterTierSet.count, totalPairs))
    md += String(format: "| **anchor+assoc+nikl(원본, native-tag-fixed) — upper bound** | **%d** | **%.1f%%** |\n\n",
        rawTierSet.count, pct(rawTierSet.count, totalPairs))

    md += "**The 3-filter tier is provisional and unvalidated — K1b must resolve where in this "
        + "bracket coverage actually lands usable-quality-wise.** Usable coverage is bounded below "
        + "by anchor+assoc (\(anchorAssocSet.count), \(String(format: "%.1f", pct(anchorAssocSet.count, totalPairs)))%, "
        + "synonym/collocate donors only, no NIKL at all) and above by the native-tag-fixed-but-"
        + "otherwise-unfiltered union (\(rawTierSet.count), \(String(format: "%.1f", pct(rawTierSet.count, totalPairs)))%). "
        + "**Do not present any single number from this table as \"the\" K1a coverage headline.**\n\n"

    md += "**On the 8,127 denominator**: dropped everywhere except the anchor-alone row per "
        + "coordinator review — K1 donor pairs are not confined to the anchor-having subset (NIKL "
        + "and assoc cover pairs anchors.tsv has nothing for at all), so union/cumulative tiers "
        + "expressed as \"% of 8,127\" can exceed 100% and are not meaningful. Anchor-alone against "
        + "8,127 (the pre-registered baseline's own denominator): \(anchorOnlySet.count)/\(anchorHavingPairs8127) "
        + "= \(String(format: "%.1f", pct(anchorOnlySet.count, anchorHavingPairs8127)))% (pre-registered reference: "
        + "1,536/8,127 = 18.9% — comfortably cleared).\n\n"

    md += "## D1 대조, per tier\n\n"
    md += "D1 seed-bearing pairs (level=token, in_target_inventory=1): **\(d1Pairs.count)** (reproduces 8,379/19,490 = 43.0% exactly).\n\n"
    let tiers: [(String, Set<PairKey>)] = [
        ("anchor+assoc (lower bound)", anchorAssocSet),
        ("anchor+assoc+nikl(3중 필터, provisional)", threeFilterTierSet),
        ("anchor+assoc+nikl(원본, upper bound)", rawTierSet),
    ]
    md += "| tier | K1 pairs | intersection | union | **K1-only, no D1 seed** | D1-only, no K1 donor |\n|---|---:|---:|---:|---:|---:|\n"
    for (label, set) in tiers {
        let c = compareToD1(label: label, k1Set: set, d1Pairs: d1Pairs)
        md += "| \(label) | \(c.k1Count) | \(c.intersection) | \(c.union) | **\(c.k1OnlyNoD1)** | \(c.d1OnlyNoK1) |\n"
    }
    md += "\n**The complementarity claim shrinks under filtering** — report per tier, never as a single number. "
        + "At the provisional 3-filter tier, K1 still adds meaningful pairs D1 has zero seed evidence for, "
        + "but far fewer than the unfiltered union suggested.\n\n"

    md += "## Scale diagnostic — re-measured after the POS fix\n\n"
    md += String(format: "- Registration attempt pass (official tier: anchor+nikl-raw+assoc, native-tag-fixed): %.1fs, %d successful, %d failed attempts logged\n",
        registrationElapsed, officialCoveredSet.count, failureCount)
    md += String(format: "- Build time (init -> build()): baseline (0 registrations) = %.3fs, official pass (%d registrations) = %.3fs "
        + "(pure build() call alone = %.3fs)\n", baselineBuildTime, officialCoveredSet.count, aliasedBuildTime, aliasedBuildOnlyTime)
    md += String(format: "- Parse regression on the %d-row eval set: **%d/%d** (pre-fix baseline was **75/258** — same eval set, same "
        + "registration count ballpark since the official tier is still the native-tag-fixed \"raw\"/upper-bound tier)\n",
        evalSentenceCount, regressions.count, evalSentenceCount)
    let selfFlip = regressions.filter { $0.category == "selfFlipOnly" }
    let spillover = regressions.filter { $0.category == "spillover" }
    let segChanged = regressions.filter { $0.category == "segmentationChanged" }
    md += "- Regression breakdown by mechanism:\n"
    md += String(format: "  - **selfFlipOnly**: %d (pre-fix: 64)\n", selfFlip.count)
    md += String(format: "  - **spillover**: %d (pre-fix: 5)\n", spillover.count)
    md += String(format: "  - **segmentationChanged**: %d (pre-fix: 6)\n\n", segChanged.count)
    if regressions.count < 75 {
        md += "The POS fix reduced regressions from 75/258 to \(regressions.count)/258 "
            + "(\(String(format: "%.0f", Double(75 - regressions.count) / 75.0 * 100))% reduction), confirming the "
            + "NNG/NNP cross-tagging category error was the dominant cause, not incidental scale noise.\n\n"
    } else if regressions.count == 75 {
        md += "Regression count is UNCHANGED from the pre-fix run (75/258) — the POS fix did not reduce regressions "
            + "at the official (upper-bound/raw) tier; investigate before trusting this tier for anything beyond coverage measurement.\n\n"
    } else {
        md += "Regression count INCREASED after the fix (\(regressions.count) vs 75 pre-fix) — unexpected, flag for review "
            + "rather than accept silently.\n\n"
    }
    if !regressions.isEmpty {
        md += "First \(min(5, regressions.count)) regressions (any category):\n\n"
        for r in regressions.prefix(5) { md += "- `\(r.sentence)`\n  - before: `\(r.before)`\n  - after: `\(r.after)`\n" }
        md += "\n"
    }
    md += "**This diagnostic is reported as-is, not tuned** (계획 §13 정지선 — the eval set is direction-only here).\n\n"

    // --- optional illustration: 수도 spot check, from the official (upper-bound) pass ---
    md += "## Illustration only — 수도 spot check (NOT a quality metric; K1b owns quality)\n\n"
    let sudoDonors = donorRowsForSpotCheck.filter { $0.reading == "수도" }.sorted { $0.senseId < $1.senseId }
    if sudoDonors.isEmpty {
        md += "수도 has no registered donors in the official pass.\n\n"
    } else {
        md += "Registered senses for 수도 (official/upper-bound tier):\n\n| sense_id | candidate | donor | donor_pos | source |\n|---:|---|---|---|---|\n"
        for d in sudoDonors {
            md += "| \(d.senseId) | \(d.candidate) | \(d.donor) | \(d.donorPos) | \(d.source) |\n"
        }
        md += "\n"
    }

    try md.write(to: Paths.outDir.appendingPathComponent("k1a-coverage.md"), atomically: true, encoding: .utf8)
    print("wrote \(Paths.outDir.appendingPathComponent("k1a-coverage.md").path)")
}
