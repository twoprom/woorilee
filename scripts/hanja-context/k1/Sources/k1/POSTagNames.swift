// Byte-value -> tag-name mapping, mirroring Kiwi/bindings/swift/Sources/Kiwi/POSTag.swift's
// `description` switch EXACTLY. This must be used instead of the raw C string API
// (`kiwi_res_tag`) for anything that has to match the collector's morpheme-space contract:
// kiwi_res_tag() returns a richer C++-internal tag spelling (observed: "VV-R" for some regular
// verbs) that does NOT match POSTag.description's convention (always "VV" for regular, "-I"
// suffix only for the irregular flag bit 0x80) — the Kiwi Swift package's Token type never calls
// kiwi_res_tag() at all, it decodes kiwi_token_info_t.tag (the numeric byte) through
// POSTag(rawValue:). Using kiwi_res_tag()'s string directly caused a real verify-contract
// mismatch (받/VV-R vs 받/VV) during K1a development — see report.
func posTagName(rawValue: UInt8) -> String {
    switch rawValue {
    case 0: return "UNK"
    case 1: return "NNG"
    case 2: return "NNP"
    case 3: return "NNB"
    case 4: return "VV"
    case 5: return "VA"
    case 6: return "MAG"
    case 7: return "NR"
    case 8: return "NP"
    case 9: return "VX"
    case 10: return "MM"
    case 11: return "MAJ"
    case 12: return "IC"
    case 13: return "XPN"
    case 14: return "XSN"
    case 15: return "XSV"
    case 16: return "XSA"
    case 17: return "XSM"
    case 18: return "XR"
    case 19: return "VCP"
    case 20: return "VCN"
    case 21: return "SF"
    case 22: return "SP"
    case 23: return "SS"
    case 24: return "SSO"
    case 25: return "SSC"
    case 26: return "SE"
    case 27: return "SO"
    case 28: return "SW"
    case 29: return "SB"
    case 30: return "SL"
    case 31: return "SH"
    case 32: return "SN"
    case 33: return "W_URL"
    case 34: return "W_EMAIL"
    case 35: return "W_MENTION"
    case 36: return "W_HASHTAG"
    case 37: return "W_SERIAL"
    case 38: return "W_EMOJI"
    case 39: return "JKS"
    case 40: return "JKC"
    case 41: return "JKG"
    case 42: return "JKO"
    case 43: return "JKB"
    case 44: return "JKV"
    case 45: return "JKQ"
    case 46: return "JX"
    case 47: return "JC"
    case 48: return "EP"
    case 49: return "EF"
    case 50: return "EC"
    case 51: return "ETN"
    case 52: return "ETM"
    case 53: return "Z_CODA"
    case 54: return "Z_SIOT"
    case 55: return "USER0"
    case 56: return "USER1"
    case 57: return "USER2"
    case 58: return "USER3"
    case 59: return "USER4"
    case 132: return "VV-I"
    case 133: return "VA-I"
    case 137: return "VX-I"
    case 144: return "XSA-I"
    default: return "UNK"
    }
}
